function parseRA(s) { const [h, m, sec] = s.split(' ').map(Number); return ((h + m / 60 + sec / 3600) / 24) * Math.PI * 2; }
function parseDec(s) {
  const sign = s.trim()[0] === '-' ? -1 : 1;
  const [d, m] = s.replace(/[+-]/, '').split(' ').map(Number);
  return sign * (d + m / 60) * Math.PI / 180;
}

